import archiver from 'archiver';
import { NextResponse } from 'next/server';
import { codeGenerationSchema } from '@/lib/services/code-generation';

export const runtime = 'nodejs';
export const maxDuration = 30;

export async function POST(request: Request) {
  let input: unknown;
  try {
    input = await request.json();
  } catch {
    return NextResponse.json({ error: 'Send a valid project result.' }, { status: 400 });
  }

  const parsed = codeGenerationSchema.safeParse(input);
  if (!parsed.success) {
    return NextResponse.json({ error: 'Project files are invalid or contain an unsafe path.' }, { status: 400 });
  }

  try {
    const archive = archiver('zip', { zlib: { level: 8 } });
    const chunks: Buffer[] = [];
    const output = new Promise<Buffer>((resolve, reject) => {
      archive.on('data', (chunk: Buffer) => chunks.push(Buffer.from(chunk)));
      archive.on('end', () => resolve(Buffer.concat(chunks)));
      archive.on('error', reject);
    });

    for (const file of parsed.data.files) {
      archive.append(file.code, { name: file.path });
    }
    const notes = [
      `# ${parsed.data.title}`,
      '',
      parsed.data.summary,
      '',
      ...(parsed.data.runInstructions.length ? ['## Run instructions', ...parsed.data.runInstructions.map((item, index) => `${index + 1}. ${item}`), ''] : []),
      ...(parsed.data.notes.length ? ['## Notes', ...parsed.data.notes.map((item) => `- ${item}`)] : []),
      '',
      '> Generated by DevPilot Code Studio. Review the source and dependencies before running it.'
    ].join('\n');
    if (!parsed.data.files.some((file) => file.path.toLowerCase() === 'devpilot-notes.md')) {
      archive.append(notes, { name: 'DEVPILOT-NOTES.md' });
    }

    await archive.finalize();
    const buffer = await output;
    return new Response(new Uint8Array(buffer), {
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': 'attachment; filename="devpilot-generated-project.zip"',
        'Content-Length': String(buffer.length),
        'Cache-Control': 'no-store',
        'X-Content-Type-Options': 'nosniff'
      }
    });
  } catch {
    return NextResponse.json({ error: 'Could not create the project ZIP.' }, { status: 500 });
  }
}
